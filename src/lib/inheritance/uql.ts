const withoutStrings = maskUqlStrings;

// Backend value lists accept literals only, including lists generated by friendly operators.
function hasNestedInList(query: string): boolean {
  const text = maskUqlStrings(query);
  const pattern = /\b(?:not\s+)?in\s*\(|\b(?:overlaps|has_all|contains_all|all)\s*\(\s*[^,()]+\s*,\s*\(/gi;
  let match: RegExpExecArray | null;
  while ((match = pattern.exec(text))) {
    const start = pattern.lastIndex - 1;
    let depth = 0;
    for (let index = start; index < text.length; index++) {
      if (text[index] === '(' && ++depth > 1) return true;
      if (text[index] === ')' && --depth === 0) { pattern.lastIndex = index + 1; break; }
    }
  }
  return false;
}

export function validateInheritanceUql(value: string, compiler?: UqlCompiler): UqlValidation {
  const normalized = value.trim().replace(/;\s*$/, '').trim();
  if (!normalized) return { state: 'empty', message: '', compiled: '', explicitFollowerFilter: false };
  const delimiters = uqlDelimiterIssue(normalized); if (delimiters) return { ...delimiters, compiled: '', explicitFollowerFilter: false };
  const editable = normalized.replace(/^where\b\s*/i, '').trim();
  if (!editable || /(?:\bwhere\b|\band\b|\bor\b|\bnot\b|\bin\b|\bbetween\b|\blike\b|\bilike\b|\bmod\b|\bhas\b|\bhas\s+any\b|\bhas\s+all\b|\bdoes\s+not\s+have\b|\bcontains\b|\bcontains\s+any\b|\bcontains\s+all\b|[,(+\-*\/%]|=|!=|<>|<=|>=|<|>)$/i.test(editable)) return { state: 'incomplete', message: 'Finish the predicate', compiled: '', explicitFollowerFilter: false };
  if (/\b(?:in|has|has_all|contains_all|overlaps)\s*\[\s*\]/i.test(withoutStrings(editable))) return { state: 'incomplete', message: 'Choose at least one value', compiled: '', explicitFollowerFilter: false };
  if (/(?:^|[\s(])(?:has\s+any|has\s+all|contains\s+any|contains\s+all|not\s+in|in)\s*\(\s*\)(?=\s*(?:\)|;|$|\band\b|\bor\b))/i.test(withoutStrings(editable)) || /\b(?:overlaps|has_all|contains_all|all)\s*\(\s*[^,()]+\s*,\s*\(\s*\)\s*\)/i.test(withoutStrings(editable))) return { state: 'incomplete', message: 'Choose at least one skill', compiled: '', explicitFollowerFilter: false };
  const continuation = editable.match(/(?:\d|'|"|\))\s+([A-Za-z]+)$/)?.[1]?.toLowerCase();
  if (continuation && ['a', 'an', 'o'].includes(continuation)) return { state: 'incomplete', message: 'Finish the boolean operator', compiled: '', explicitFollowerFilter: false };

  let sortBy: InheritanceSort | undefined; const predicates: string[] = [];
  for (const clause of splitUqlClauses(editable)) {
    const directive = clause.match(/^sort(?:\s+by)?\s*(?:=|==|is)?\s*\[?\s*([^\]]+?)\s*\]?$/i);
    if (directive) {
      const requested = directive[1]?.replace(/^['"]|['"]$/g, '').trim().toLocaleLowerCase() ?? '';
      sortBy = sortAliases[requested]; if (!sortBy) return { state: 'invalid', message: `Unknown sort: ${requested}`, compiled: '', explicitFollowerFilter: false };
    } else predicates.push(clause);
  }
  const compiled = (compiler ?? new UqlCompiler()).compile(predicates.join(' and '));
  const identifierText = withoutStrings(compiled);
  if (hasNestedInList(compiled)) return { state: 'invalid', message: 'IN lists only accept literal values, not nested functions', compiled: '', sortBy, explicitFollowerFilter: false };
  for (const match of identifierText.matchAll(/[A-Za-z_][A-Za-z0-9_.]*/g)) {
    const identifier = match[0].toLowerCase().replace(/\./g, '_');
    if (fields.has(identifier) || keywords.has(identifier) || functions.has(identifier) || functionParameters.has(identifier)) continue;
    const functionCall = identifierText.slice(match.index + match[0].length).trimStart().startsWith('(');
    return { state: 'invalid', message: `Unknown field or function: ${match[0]}${functionCall ? '()' : ''}`, compiled: '', sortBy, explicitFollowerFilter: false };
  }
  if (!compiled && !sortBy) return { state: 'incomplete', message: 'Finish the predicate', compiled: '', explicitFollowerFilter: false };
  return { state: 'valid', message: 'Ready', compiled, sortBy, explicitFollowerFilter: /\b(?:follower_num|followers)\b/i.test(identifierText) };
}
